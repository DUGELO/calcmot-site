import { readFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import assert from 'node:assert/strict';
import { parse } from 'yaml';
const root=resolve(process.argv[2]);
const config=parse(await readFile(resolve(root,'.pages.yml'),'utf8'));
assert.equal(config.media.input,'media');
assert.ok(!config.media.input.startsWith('public'));
const collection=config.content.find(value=>value.name==='articles');
assert.equal(collection.path,'articles');
assert.equal(collection.filename.field,false);
assert.equal(collection.operations.rename,false);
assert.equal(collection.operations.delete,false);
assert.ok(!collection.fields.some(value=>value.name==='status'));
const publish=collection.actions.find(value=>value.name==='publish');
assert.equal(publish.scope,'entry');assert.equal(publish.confirm,false);
const workflow=parse(await readFile(resolve(root,'.github/workflows/editorial.yml'),'utf8'));
assert.deepEqual(Object.keys(workflow.on),['workflow_dispatch']);
assert.equal(workflow.concurrency.queue,'max');
assert.equal(workflow.concurrency['cancel-in-progress'],false);
console.log('Configuração privada: formulário, ações explícitas e fila de publicação válidos.');
