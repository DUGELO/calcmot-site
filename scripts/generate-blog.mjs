import { mkdir, writeFile, rm, readdir } from 'node:fs/promises';
import { resolve } from 'node:path';
import { loadPosts, listingPaths, CATEGORIES, PAGE_SIZE } from './blog/content.mjs';
import { verifySnapshot } from './editorial/snapshot.mjs';
const root = resolve(import.meta.dirname, '..');
const output = resolve(root, 'src/app/blog/generated');
await mkdir(output, { recursive: true });
// Remove obsolete optimized files so unpublished images are not retained.
await rm(resolve(root, 'public/media/blog-optimized'), { recursive: true, force: true });
const originals = await readdir(resolve(root, 'public/media/blog')).catch(error => {
  if (error.code === 'ENOENT') return []; throw error;
});
if (originals.some(name => name !== '.gitkeep')) throw new Error('Originais editoriais não podem permanecer na pasta pública.');
let posts = [];
const source = process.env.CALCMOT_CONTENT_ROOT;
if (source) {
  const contentRoot = resolve(source);
  if (contentRoot === root || contentRoot.startsWith(resolve(root, 'public'))) throw new Error('Conteúdo privado fora da pasta pública é obrigatório.');
  const snapshot = await verifySnapshot(contentRoot);
  posts = await loadPosts({ root, directory: resolve(contentRoot, 'articles'), mediaDirectory: resolve(contentRoot, 'media') });
  await writeFile(resolve(root, 'public/blog-release.json'), JSON.stringify({
    releaseId: snapshot.releaseId, codeRevision: snapshot.codeRevision, snapshotDigest: snapshot.snapshotDigest,
  }) + '\n');
} else {
  await rm(resolve(root, 'public/blog-release.json'), { force: true });
}
const paths = listingPaths(posts);
const manifest = { paths, slugs: posts.map(p => p.slug), redirects: Object.fromEntries(posts.flatMap(p => p.aliases.map(alias => [alias, p.slug]))) };
await rm(resolve(output, 'articles'), { recursive: true, force: true });
await mkdir(resolve(output, 'articles'), { recursive: true });
for (const post of posts) await writeFile(resolve(output, 'articles', post.slug + '.ts'), 'export default ' + JSON.stringify(post.html) + ';\n');
await writeFile(resolve(output, 'bodies.ts'), 'export const BLOG_BODIES: Readonly<Record<string, () => Promise<string>>> = {\n' + posts.map(post => JSON.stringify(post.slug) + ': () => import("./articles/' + post.slug + '").then(module => module.default),').join('\n') + '\n};\n');
await writeFile(resolve(output, 'posts.ts'), `// Generated by npm run content:generate; published articles only.\nimport type { BlogSummary } from '../blog.models';\nexport const BLOG_POSTS: readonly BlogSummary[] = ${JSON.stringify(posts.map(({ html, ...summary }) => summary), null, 2)};\nexport const BLOG_CATEGORIES: Readonly<Record<string, string>> = ${JSON.stringify(CATEGORIES)};\nexport const BLOG_PAGE_SIZE = ${PAGE_SIZE};\n`);
await writeFile(resolve(output, 'routes.ts'), `// Generated published routes.\nexport const BLOG_LIST_PATHS: readonly string[] = ${JSON.stringify(paths)};\nexport const BLOG_SLUGS: readonly string[] = ${JSON.stringify(manifest.slugs)};\nexport const BLOG_REDIRECTS: Readonly<Record<string, string>> = ${JSON.stringify(manifest.redirects)};\n`);
await writeFile(resolve(output, 'sitemap.json'), JSON.stringify({ paths, posts: posts.map(({ slug, updatedAt, canonical, category }) => ({ slug, updatedAt, canonical, category })) }));
await mkdir(resolve(root, 'cloudflare/generated'), { recursive: true });
await writeFile(resolve(root, 'cloudflare/generated/blog-manifest.mjs'), `export default ${JSON.stringify(manifest)};\n`);
console.log(`Blog: ${posts.length} artigos publicados, ${paths.length} páginas de listagem.`);
