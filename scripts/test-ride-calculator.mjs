import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';
import vm from 'node:vm';
const source = readFileSync('src/app/core/calculator/ride-calculator.ts','utf8');
const js = ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const exports={};vm.runInNewContext(js,{exports});
const calc=exports.calculateRide;
const base={fare:'18,00',pickupKm:'2',tripKm:'10',tripMinutes:'20',pickupMinutes:'4',costPerKm:'0,550'};
const ok=calc(base);assert.equal(ok.ok,true);assert.equal(ok.metrics.totalMeters,12000);assert.equal(ok.metrics.totalMinutes,24);assert.equal(ok.metrics.grossPerKmCents,150);assert.equal(ok.metrics.grossPerHourCents,4500);assert.equal(ok.metrics.costCents,660);assert.equal(ok.metrics.balanceCents,1140);
assert.equal(calc({...base,costPerKm:''}).metrics.balanceCents,null);
assert.equal(calc({...base,tripKm:'0'}).ok,true);
assert.equal(calc({...base,tripKm:'0',pickupKm:'0'}).ok,false);
assert.equal(calc({...base,tripMinutes:'0',pickupMinutes:'0'}).ok,false);
assert.equal(calc({...base,fare:'-1'}).ok,false);
assert.equal(calc({...base,fare:'1.000,00'}).ok,false);
assert.equal(calc({...base,tripKm:'1000',pickupKm:'1'}).ok,false);
assert.equal(calc({...base,tripMinutes:'1440',pickupMinutes:'1'}).ok,false);
assert.equal(calc({...base,costPerKm:'0'}).metrics.costCents,0);
console.log('Motor financeiro: 10 cenários OK.');
